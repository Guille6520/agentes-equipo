import { boolean, integer, jsonb, pgEnum, pgTable, serial, text, timestamp } from "drizzle-orm/pg-core";
import type { AcceptanceItemDTO } from "../lib/types";

export const agentEnum = pgEnum("agent", ["orchestrator", "develop", "testing"]);
export const runStatusEnum = pgEnum("run_status", ["running", "passed", "failed"]);
export const taskStatusEnum = pgEnum("task_status", [
  "pending",
  "running",
  "failed",
  "passed",
]);

/** One user request ("add a contact page") processed by the agent team. */
export const runs = pgTable("runs", {
  id: serial("id").primaryKey(),
  request: text("request").notNull(),
  status: runStatusEnum("status").notNull().default("running"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  finishedAt: timestamp("finished_at"),
  // --- Motor (columnas aditivas) ---
  /** Solo los runs creados con el motor se avanzan; los de demo (seed) quedan intactos. */
  engineManaged: boolean("engine_managed").notNull().default(false),
  /** Lease: quien tenga el token y locked_until > now() es el único que avanza el run. */
  lockedUntil: timestamp("locked_until"),
  lockToken: text("lock_token"),
  /** Pasos seguidos que fallaron por los modelos (ambos proveedores); a los 3 el run falla. */
  stepErrors: integer("step_errors").notNull().default(0),
  /** Modo demo: Develop entrega a propósito una primera versión con un defecto para mostrar el bucle. */
  demoForceFailure: boolean("demo_force_failure").notNull().default(false),
});

/** Subtasks created by the Orchestrator and assigned to Develop. */
export const tasks = pgTable("tasks", {
  id: serial("id").primaryKey(),
  runId: integer("run_id")
    .notNull()
    .references(() => runs.id, { onDelete: "cascade" }),
  title: text("title").notNull(),
  description: text("description").notNull(),
  status: taskStatusEnum("status").notNull().default("pending"),
  attempts: integer("attempts").notNull().default(0),
  lastFeedback: text("last_feedback"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at").notNull().defaultNow(),
  // --- Motor (columnas aditivas) ---
  /** Quién debe actuar sobre la tarea: "develop" (generar/corregir) o "testing" (revisar). */
  phase: text("phase").notNull().default("develop"),
  /** Perfil de checks: "contact-form" (incluye checks de formulario) o "basic". */
  checkProfile: text("check_profile").notNull().default("basic"),
  /**
   * Criterios de aceptación del Orquestador (vocabulario cerrado, ver src/lib/testing/acceptance.ts)
   * con el estado de la última revisión de Testing. Nullable: las tareas antiguas no tienen.
   */
  acceptance: jsonb("acceptance").$type<AcceptanceItemDTO[]>(),
});

/** Versioned files generated by Develop for a task. */
export const files = pgTable("files", {
  id: serial("id").primaryKey(),
  taskId: integer("task_id")
    .notNull()
    .references(() => tasks.id, { onDelete: "cascade" }),
  path: text("path").notNull(),
  content: text("content").notNull(),
  version: integer("version").notNull().default(1),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

/** Activity log shown live on screen: what each agent is doing. */
export const events = pgTable("events", {
  id: serial("id").primaryKey(),
  runId: integer("run_id")
    .notNull()
    .references(() => runs.id, { onDelete: "cascade" }),
  taskId: integer("task_id").references(() => tasks.id, { onDelete: "cascade" }),
  agent: agentEnum("agent").notNull(),
  message: text("message").notNull(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// --- Evaluación de modelos (tablas aditivas, independientes de los runs de los agentes) ---

/** Una evaluación de modelos: el benchmark manual del 23/11/2026 o un relanzamiento desde la app. */
export const evalRuns = pgTable("eval_runs", {
  id: serial("id").primaryKey(),
  /** "manual-2026-11-23" (histórico cargado por seed) o "app" (relanzado desde /evals). */
  origin: text("origin").notNull(),
  /** "running" | "done" | "abandoned". */
  status: text("status").notNull().default("running"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  finishedAt: timestamp("finished_at"),
  /** Lease por evaluación: solo una función ejecuta un paso a la vez. */
  lockedUntil: timestamp("locked_until"),
  lockToken: text("lock_token"),
});

/** Resultado de una prueba (orchestrator | develop | testing) de un modelo dentro de una evaluación. */
export const evalResults = pgTable("eval_results", {
  id: serial("id").primaryKey(),
  runId: integer("run_id")
    .notNull()
    .references(() => evalRuns.id, { onDelete: "cascade" }),
  model: text("model").notNull(),
  provider: text("provider").notNull(),
  test: text("test").notNull(),
  /** Orden de ejecución dentro de la evaluación (0..n). */
  step: integer("step").notNull().default(0),
  /** "pending" | "done" | "not_measured" (el informe manual no lo midió). */
  status: text("status").notNull().default("pending"),
  /** null = sin veredicto (pendiente o no medido). */
  ok: boolean("ok"),
  metrics: jsonb("metrics").$type<Record<string, unknown>>(),
  error: text("error"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  finishedAt: timestamp("finished_at"),
});
